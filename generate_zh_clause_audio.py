#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Clause audio + timeline for the original Chinese lessons zh0–zh7 (ClausePlayer 分段跟读).

Outputs (edge-tts, same voices/rates as generate_all_clause_audio.py / generate_shizi12_audio.py):
- audio/<id>_clause/st{n}_c{m}.mp3   clause clips          (zh-CN-XiaoxiaoNeural, -10%)
- audio/<id>_ko/st{n}.mp3            Korean story lines    (ko-KR-SunHiNeural, -8%)
- data/zh-lesson-clauses.js          window.ALL_LESSON_CLAUSES.<id> = {...} for every zh lesson

The sentence-level zh/en/ja audio (audio/<id>/, _en, _ja) comes from generate_zh_audio.py.
Clause text lives in zh_lesson_clauses.py; run build_chinese_lessons.py afterwards (or before) to
regenerate the pages. Existing MP3s are kept; delete a file to re-synthesise it.
"""
import asyncio
import json
import subprocess
from pathlib import Path

import edge_tts

from build_chinese_lessons import LESSONS
from zh_lesson_clauses import CLAUSES, validate

ROOT = Path(__file__).resolve().parent
ZH_VOICE, CLAUSE_RATE = "zh-CN-XiaoxiaoNeural", "-10%"
KO_VOICE, KO_RATE = "ko-KR-SunHiNeural", "-8%"
BUNDLE = ROOT / "data" / "zh-lesson-clauses.js"


def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                          "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
                         capture_output=True, text=True, check=True)
    return round(float(out.stdout.strip()), 3)


async def synth(sem, path, text, voice, rate):
    if path.exists() and path.stat().st_size > 800:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    async with sem:
        for attempt in range(3):
            try:
                await edge_tts.Communicate(text, voice, rate=rate).save(str(path))
                break
            except Exception as err:  # network hiccups: retry, then report
                if attempt == 2:
                    raise RuntimeError(f"TTS failed for {path.relative_to(ROOT)} ({text}): {err}")
                await asyncio.sleep(1 + attempt)
    print(f"OK  {path.relative_to(ROOT)}")


def lesson_meta(lesson):
    lid = lesson["id"]
    g = 0.0
    sentences = []
    for si, (s, (ko, clauses)) in enumerate(zip(lesson["story"], CLAUSES[lid])):
        start, local, items = g, 0.0, []
        for ci, (czh, cpy, cen, cjp, cko) in enumerate(clauses):
            cid = f"{s['id']}_c{ci + 1}"
            d = duration(ROOT / "audio" / f"{lid}_clause" / f"{cid}.mp3")
            items.append({"id": cid, "sentId": s["id"], "sentIndex": si, "clauseIndex": ci,
                          "zh": czh, "py": cpy, "en": cen, "jp": cjp, "ko": cko,
                          "audioUrl": f"audio/{lid}_clause/{cid}.mp3", "duration": d,
                          "sentOffsetStart": round(local, 3), "sentOffsetEnd": round(local + d, 3),
                          "globalOffsetStart": round(g, 3), "globalOffsetEnd": round(g + d, 3)})
            local += d
            g += d
        sentences.append({"sentId": s["id"], "sentIndex": si, "sentZh": s["zh"], "sentPy": s["py"],
                          "sentEn": s["en"], "sentJp": s.get("jp", ""), "sentKo": ko, "clauses": items,
                          "duration": round(local, 3), "globalOffsetStart": round(start, 3),
                          "globalOffsetEnd": round(g, 3), "clauseCount": len(items)})
    return {"lesson": lid, "title": lesson["header_title"], "totalSentences": len(sentences),
            "totalClauses": sum(x["clauseCount"] for x in sentences),
            "totalDuration": round(g, 3), "sentences": sentences}


async def main():
    validate(LESSONS)
    sem = asyncio.Semaphore(6)
    jobs = []
    for lesson in LESSONS:
        lid = lesson["id"]
        for s, (ko, clauses) in zip(lesson["story"], CLAUSES[lid]):
            jobs.append(synth(sem, ROOT / "audio" / f"{lid}_ko" / f"{s['id']}.mp3", ko, KO_VOICE, KO_RATE))
            for ci, c in enumerate(clauses):
                jobs.append(synth(sem, ROOT / "audio" / f"{lid}_clause" / f"{s['id']}_c{ci + 1}.mp3",
                                  c[0], ZH_VOICE, CLAUSE_RATE))
    await asyncio.gather(*jobs)

    bundle = {lesson["id"]: lesson_meta(lesson) for lesson in LESSONS}
    BUNDLE.write_text(
        "// Generated by generate_zh_clause_audio.py — clause timelines for zh0–zh7 (ClausePlayer).\n"
        "window.ALL_LESSON_CLAUSES = window.ALL_LESSON_CLAUSES || {};\n"
        "Object.assign(window.ALL_LESSON_CLAUSES, "
        + json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ");\n",
        encoding="utf-8")
    for lid, m in bundle.items():
        print(f"{lid}: {m['totalSentences']} sentences, {m['totalClauses']} clauses, {m['totalDuration']}s")
    print(f"-> {BUNDLE.relative_to(ROOT)} ({BUNDLE.stat().st_size} bytes)")


if __name__ == "__main__":
    asyncio.run(main())
