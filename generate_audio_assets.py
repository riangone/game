async def generate_single(semaphore, lang, key, text, voice, out_dir):
    async with semaphore:
        safe_name = re.sub(r'[\/\\:*?"<>|]', '', key).strip()
        if not safe_name:
            return
        out_path = out_dir / f"{safe_name}.mp3"
        if out_path.exists() and out_path.stat().st_size > 500:
            return

        try:
            communicate = edge_tts.Communicate(text, voice)
            await communicate.save(str(out_path))
        except Exception as e:
            print(f"[{lang}] Error generating {safe_name} ({text}): {e}", file=sys.stderr)

async def main():
    print("Starting Audio Generation...")
    print(f"Items to generate: JA={len(JA_ITEMS)}, ZH={len(ZH_ITEMS)}, KO={len(KO_ITEMS)}")

    ja_dir = AUDIO_DIR / "ja"
    ko_dir = AUDIO_DIR / "ko"
    zh_dir = AUDIO_DIR / "zh"

    ja_dir.mkdir(parents=True, exist_ok=True)
    ko_dir.mkdir(parents=True, exist_ok=True)
    zh_dir.mkdir(parents=True, exist_ok=True)

    semaphore = asyncio.Semaphore(12)
    tasks = []

    for k, text in JA_ITEMS.items():
        tasks.append(generate_single(semaphore, "JA", k, text, JA_VOICE, ja_dir))

    for k, text in ZH_ITEMS.items():
        tasks.append(generate_single(semaphore, "ZH", k, text, ZH_VOICE, zh_dir))

    for k, text in KO_ITEMS.items():
        tasks.append(generate_single(semaphore, "KO", k, text, KO_VOICE, ko_dir))

    await asyncio.gather(*tasks)
    print("Base audio generation complete. Now executing precision tone sculpting...")
    import generate_accurate_tones
    await generate_accurate_tones.main()
    print("All audio generation complete!")
    print("Files in ja:", len(list(ja_dir.glob("*.mp3"))))
    print("Files in zh:", len(list(zh_dir.glob("*.mp3"))))
    print("Files in ko:", len(list(ko_dir.glob("*.mp3"))))

if __name__ == "__main__":
    asyncio.run(main())
